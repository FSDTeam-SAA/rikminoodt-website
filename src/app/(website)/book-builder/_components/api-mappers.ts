export function mapAge(rawAge: string | null): "0-2" | "3-5" | "3-9" | "10+" {
  if (!rawAge) return "3-5";
  if (rawAge.includes("0-2")) return "0-2";
  if (rawAge.includes("3-5")) return "3-5";
  if (rawAge.includes("5-9") || rawAge.includes("3-9")) return "3-9";
  if (rawAge.includes("10+") || rawAge.toLowerCase().includes("adult")) return "10+";
  return "3-5";
}

export function mapTheme(rawTheme: string | null): string {
  if (!rawTheme) return "FAIRYTALES_AND_MAGIC";
  return THEME_MAP[rawTheme] || "FAIRYTALES_AND_MAGIC";
}

export function mapSubject(rawSubject: string | null, mappedTheme: string): string {
  const allowed = THEME_SUBJECT_MAP[mappedTheme] || THEME_SUBJECT_MAP.FAIRYTALES_AND_MAGIC;
  if (rawSubject && SUBJECT_MAP[rawSubject] && allowed.includes(SUBJECT_MAP[rawSubject])) {
    return SUBJECT_MAP[rawSubject];
  }
  // If rawSubject is directly one of the enum values in allowed
  if (rawSubject && allowed.includes(rawSubject)) {
    return rawSubject;
  }
  return allowed[0] || "UNICORNS";
}

